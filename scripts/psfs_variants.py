#!/usr/bin/env python3
"""psfs_variants.py - generate several layout variants of the PSFS sheets, lint and score each, keep the best.

Variants: box width (300..460 px, wrap width follows), packing order (register order or tallest-first) and PSFS page count. Score (lower is better):
  1000 x lint errors  +  10 x text overlaps on the PSFS sheets  +  5 x PSFS sheets  -  20 x mean fill of the drawing area
Usage: python3 scripts/psfs_variants.py [--apply] [--report out.md]   (--apply writes the winning settings into urea_psfs.py)
"""
import sys, os, re, itertools
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_pid_urea_package as G
import urea_psfs, psfs_lint

WIDTHS = (300, 340, 380, 420, 460); PACKS = ("shelf", "ffd")


def run(colw, pack):
    urea_psfs.COLW = colw; urea_psfs.PACK = pack; urea_psfs.WRAPN = int((colw - 44) / 4.55)
    pkg = G.build_package()[0]; F = psfs_lint.lint(pkg)
    ps = [s for s in pkg.sheets if getattr(s, "psfs", False)]
    ov = sum(len(G.overlaps(s)[0]) + len(G.overlaps(s)[1]) for s in ps)
    area = (urea_psfs.BOTTOM - urea_psfs.TOP) * 1560
    fill = sum(sum(b["w"] * b["h"] for b in s.psfs_boxes) / area for s in ps) / len(ps)
    err = sum(1 for f in F if f.sev == "E")
    return dict(colw=colw, pack=pack, wrap=urea_psfs.WRAPN, sheets=len(ps), errors=err, overlaps=ov, fill=fill, score=1000 * err + 10 * ov + 5 * len(ps) - 20 * fill)


def main():
    argv = sys.argv[1:]; res = [run(w, p) for w, p in itertools.product(WIDTHS, PACKS)]; res.sort(key=lambda r: r["score"])
    L = ["| rank | box width | wrap | packing | PSFS sheets | lint errors | text overlaps | mean fill | score |", "|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(res, 1): L.append(f"| {i} | {r['colw']} | {r['wrap']} | {r['pack']} | {r['sheets']} | {r['errors']} | {r['overlaps']} | {r['fill']:.2f} | {r['score']:.1f} |")
    print("\n".join(L)); best = res[0]; print("best:", best)
    if "--report" in argv:
        open(argv[argv.index("--report") + 1], "w").write("# PSFS layout variants\n\nGenerated by `scripts/psfs_variants.py`; each row is a full package build, linted and scored (lower score is better).\n\n" + "\n".join(L) + f"\n\nWinner: box width {best['colw']}, packing {best['pack']}.\n")
    if "--apply" in argv:
        p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "urea_psfs.py"); s = open(p).read()
        s = re.sub(r"^COLW, GAP, X0, TOP, BOTTOM = \d+,", f"COLW, GAP, X0, TOP, BOTTOM = {best['colw']},", s, flags=re.M)
        s = re.sub(r'^PACK = "\w+"', f'PACK = "{best["pack"]}"', s, flags=re.M)
        s = re.sub(r"^WRAPN = \d+", f"WRAPN = {best['wrap']}", s, flags=re.M); open(p, "w").write(s); print("applied to urea_psfs.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())

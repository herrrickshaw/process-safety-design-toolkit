#!/usr/bin/env python3
"""Run the urea balance twice (Rev B: UREA_REVC=0, Rev C rebase: default) at the 3,850 t/d nameplate and write docs/pid/urea_detail/REBASE_REVC.md/.csv:
the changed inputs with their sources and the metrics before and after against the benchmark values read in PROCESS_BENCHMARKS.md (row numbers)."""
import os, sys, json, subprocess, csv
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
PROBE = r'''
import sys, json; sys.path.insert(0, %r)
import gen_pid_urea as g
from urea_basis import K
S, M = g.S, g.M
dry = sum(S[12].values())
maf = 1 - g.COAL["ash"] - g.COAL["moisture"]
out = dict(coal=M[1]*3.6*K, o2=M[2]*3.6*K, syngas=M[4]*3.6*K, ht_steam=M[6]*3.6*K, acid=M[11]*3.6*K, acid_h2s_mol=100*S[11]["H2S"]/sum(S[11].values()),
  co2_urea=M[10]*3.6*K, co2_surplus=M[20]*3.6*K, treated=M[12]*3.6*K, makeup=M[15]*3.6*K, recycle=M[27]*3.6*K, air=M[25]*3.6*K,
  cge=g.CGE_B*100, h2o_co=(S[4]["H2O"]+S[6]["H2O"])/S[4]["CO"], co_conv=100*(1-S[9]["CO"]/S[4]["CO"]), nh3_exit=100*2*g.SPASS_CONV/(4-2*g.SPASS_CONV),
  oxides=100*(S[12]["CO"]+S[12]["CO2"])/dry, asu_mw=g.ASU_MW*K, o2_per_maf=M[2]/M[1]/maf, c_conv=g.C_CONV*100, ash=100*g.COAL["ash"])
print("JSON" + json.dumps(out))
'''
def run(rev):
    env = dict(os.environ, UREA_REVC=rev)
    r = subprocess.run([sys.executable, "-c", PROBE % HERE], capture_output=True, text=True, env=env, cwd=HERE)
    line = [l for l in r.stdout.splitlines() if l.startswith("JSON")]
    assert line, r.stderr[-400:]
    return json.loads(line[0][4:])
B, C = run("0"), run("1")
ROWS = [  # key, label, unit, source value or None, source text, benchmark row
    ("coal", "Coal + petcoke feed to gasification", "t/h", 149.5, "Talcher EIA 112.1 coal + 37.4 petcoke (S5 p.II); PFR 144.7 (S6 Table 3.2)", "1, 2"),
    ("c_conv", "Gasifier carbon conversion", "%", 99.5, "NETL Ex. 3-74 p.238; Eurlings GTC99 Tables 4-5 98.8-99.9", "11"),
    ("h2o_co", "H2O:CO at the first shift reactor", "mol/mol", 1.8, "NETL Case 6 text p.265", "19"),
    ("co_conv", "Overall CO conversion through shift", "%", 97.8, "NETL Case 6 text p.265", "20"),
    ("cge", "Cold gas efficiency (HHV)", "%", None, "sources give 75-83 % on an LHV basis (Eurlings Tables 4-5): different basis, not compared", "15"),
    ("acid_h2s_mol", "H2S in the acid gas to Claus", "mol %", 34.0, "NETL Case 6 p.266 (Selexol); Case 5 Sulfinol 39 %", "23"),
    ("nh3_exit", "NH3 at the converter exit", "mol %", 16.9, "Talcher PFR Sec 3.3.3 p.9", "38"),
    ("asu_mw", "ASU power", "MW", None, "461.5 kWh/t O2 adopted (NETL MAC+O2 456.2, whole train 679.7 kWh/t, Ex. 3-89 p.272)", "30-32"),
    ("o2_per_maf", "O2 per t moisture-ash-free feed", "t/t", None, "0.92-1.06 t/t (Eurlings Tables 4-5); blend carbon scaling keeps O2/C", "12"),
    ("oxides", "CO + CO2 in the treated gas (methanator feed)", "mol %", 0.1, "TECHNOLOGY_SOURCES: 100-1,000 ppm typical; CO left by the shift is not removable by the AGR (N2 wash not drawn)", "55"),
    ("syngas", "Raw syngas", "t/h", None, "", ""), ("o2", "Oxygen to the gasifier", "t/h", None, "", ""), ("ht_steam", "Steam to the first shift reactor", "t/h", None, "", ""),
    ("acid", "Acid gas to sulphur recovery", "t/h", None, "", ""), ("co2_urea", "CO2 to the urea plant (stream 10)", "t/h", None, "", ""),
    ("co2_surplus", "Surplus CO2 vent (stream 20)", "t/h", None, "", ""), ("makeup", "Ammonia make-up gas (stream 15)", "t/h", None, "", ""),
    ("recycle", "Loop recycle gas (stream 27)", "t/h", None, "", ""), ("air", "Air to the ASU", "t/h", None, "", "")]
def f(x): return f"{x:,.2f}" if abs(x) < 100 else f"{x:,.1f}"
rows = []
for k, lab, u, src, st, rw in ROWS:
    dev = lambda v: "" if src is None else f"{(v / src - 1) * 100:+.1f} %"
    rows.append([lab, u, f(B[k]), f(C[k]), "" if src is None else f(src), dev(B[k]), dev(C[k]), st, rw])
hdr = ["Metric", "Unit", "Rev B", "Rev C", "Source value", "Rev B vs source", "Rev C vs source", "Source", "Benchmark row"]
with open(os.path.join(ROOT, "docs/pid/urea_detail/REBASE_REVC.csv"), "w", newline="") as fh:
    w = csv.writer(fh); w.writerow(hdr); w.writerows(rows)
md = ["# Rebase of the coal-to-urea balance on sourced values (Rev C)", "",
      "Basis: 3,850 t/d urea (Talcher-class), flows at that scale (Rev B balance x 1.2784). Rev B = `UREA_REVC=0 python3 scripts/gen_pid_urea.py`, Rev C = the default. Generated by `scripts/urea_rebase_report.py`.", "",
      "## Inputs changed (scripts/gen_pid_urea.py, block 'Rev C rebase')", "",
      "| Input | Rev B | Rev C | Source / tag |", "|---|---|---|---|",
      "| Gasifier feed | 100 % Indian coal (35 % ash) | 75 % coal + 25 % petcoke | share S (Talcher EIA 25.0 %, PFR 26.6 %); petcoke analysis A (no document read gives it; C 0.805, S 0.055, ash 0.005, moisture 0.08) |",
      "| Carbon conversion | 90 % | 99.5 % | S: NETL Ex. 3-74 p.238; Eurlings GTC99 98.8-99.9 % |",
      "| O2 and steam per kg feed | 0.55 / 0.10 | scaled by blend carbon (x 1.24) | D: O2/C and steam/O2 held at the repo values |",
      "| Steam to the first shift reactor | 0.30 of gas (H2O:CO 1.2) | H2O:CO = 1.8 | S: NETL Case 6 p.265 |",
      "| Acid gas | pure H2S | H2S 34 mol %, balance CO2 | S/A: NETL Case 6 p.266 (balance taken as CO2) |",
      "| Converter per-pass conversion | 0.19 (10.5 mol % NH3 out) | 0.289 (16.9 mol % NH3 out) | D from S: Talcher PFR Sec 3.3.3 p.9 |",
      "| CO2 removal in the AGR | 97 % | 99.95 % | A: ppm-level CO2 for ammonia synthesis (TECHNOLOGY_SOURCES.md) |",
      "| ASU power | 275 kWh/t O2 | 461.5 kWh/t O2 | D/S: AREA_20 bottom-up, NETL MAC+O2 456.2 (Ex. 3-89 p.272) |",
      "| Area 40 bed inlets | HT 280/300 C, LT 205/195 C | HT 275/300 C, LT 220/205 C | A: keep bed 1 under 520 C and LT inlet 20 C above the 197 C dew point |", "",
      "## Before and after against the sources", "", "| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
md += ["| " + " | ".join(r) + " |" for r in rows]
md += ["", "## Not changed (flowsheet decisions, flagged in docs/pid/urea_detail/PACKAGE_README.md)",
       "* Talcher's gasifier is a water quench with coal-fired boilers; this package keeps a steam-raising syngas cooler (E-101, E-132) and a small auxiliary boiler.",
       "* Talcher uses an N2 wash (no methanation); the package keeps a methanator, now on a feed with 0.79 mol % oxides (mostly CO left by the shift).",
       "* The Talcher PFR assumes NH3-stripping urea conditions (N/C 3.5, 150 bar); the package sheets are labelled CO2-stripping. Conditions are unchanged; the label needs a decision.",
       "* Petcoke composition, mill outlet moisture (2 %), gasifier count and size, and the water and steam balances are unchanged or unsourced.",
       "* The AREA_*_NOTES.md files quote numbers from the pre-rebase balance; the registers and sheets carry the rebased values."]
open(os.path.join(ROOT, "docs/pid/urea_detail/REBASE_REVC.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md[md.index("## Before and after against the sources"):md.index("## Not changed (flowsheet decisions, flagged in docs/pid/urea_detail/PACKAGE_README.md)")]))

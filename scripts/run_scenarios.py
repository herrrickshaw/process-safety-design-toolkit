"""Run the design-scenario suite and write the official report.

    python scripts/run_scenarios.py --check      run every scenario, print failures, exit 1 on any (CI / gate form)
    python scripts/run_scenarios.py --write      also (re)write docs/SCENARIO_REPORT.md
    python scripts/run_scenarios.py --update     re-capture the regression snapshots (only after a deliberate change)
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import scenario_lib as L  # noqa: E402

REPORT = os.path.join(L.ROOT, "docs", "SCENARIO_REPORT.md")


def report(data: dict, results: list[dict]) -> str:
    from process_safety import standards
    by_id = {r["id"]: r for r in results}
    kinds = ("expect", "oracle", "meta", "si_us", "regression")
    lines = ["# Scenario report", "",
             "Generated by `python scripts/run_scenarios.py --write`; do not edit by hand. Each scenario is run by `scripts/scenario_lib.py`; "
             "the kinds of check are explained in that file and summarised below.", "",
             "| Kind of check | What it proves |", "|---|---|",
             "| expect | a physical or logical bound holds (positive, below a ceiling, a flag, a category) |",
             "| oracle | an independent recomputation from first principles or from a unit definition agrees with the toolkit |",
             "| meta | a metamorphic relation holds: change one input and the answer moves the way the physics says (no remembered answer needed) |",
             "| si_us | the case typed in US-customary units through `--units us` gives the SI result (rtol 1e-9) and the US sibling keys equal the converted SI values |",
             "| regression | the current values are unchanged (a drift alarm, not independent evidence) |", ""]
    total = sum(len(r["checks"]) for r in results)
    passed = sum(c["ok"] for r in results for c in r["checks"])
    sc_ok = sum(r["ok"] for r in results)
    counts = {k: sum(1 for r in results for c in r["checks"] if c["kind"] == k) for k in kinds}
    lines += [f"**Result: {sc_ok} of {len(results)} scenarios pass; {passed} of {total} checks pass.**", "",
              "Checks by kind: " + ", ".join(f"{k} {counts[k]}" for k in kinds) + ".", "",
              "| Id | Topic | Scenario | expect | oracle | meta | si_us | regression | Verdict |", "|---|---|---|---|---|---|---|---|---|"]

    def cell(r, k):
        cs = [c for c in r["checks"] if c["kind"] == k]
        return f"{sum(c['ok'] for c in cs)}/{len(cs)}" if cs else "-"
    for sc in data["scenarios"]:
        r = by_id[sc["id"]]
        lines.append(f"| {sc['id']} | {'; '.join(sc['topics'])} | {sc['title']} | " + " | ".join(cell(r, k) for k in kinds) +
                     f" | {'PASS' if r['ok'] else 'FAIL'} |")
    lines += ["", "## Coverage of the topic map", "",
              "Every row of `python -m process_safety coverage` is either exercised by at least one scenario above or listed here as a gap with the reason.", "",
              "| Topic | Scenarios | Status in the coverage map |", "|---|---|---|"]
    ids_by_topic = {}
    for sc in data["scenarios"]:
        for t in sc["topics"]:
            ids_by_topic.setdefault(t, []).append(sc["id"])
    for t, (_, _, status) in standards.TOPICS.items():
        if t in ids_by_topic:
            lines.append(f"| {t} | {', '.join(ids_by_topic[t])} | {status.split(';')[0]} |")
    lines += ["", "### Gaps (no scenario, deliberately)", "", "| Topic | Why there is no scenario |", "|---|---|"]
    for t, why in data["gaps"].items():
        lines.append(f"| {t} | {why} |")
    lines += ["", "## Unit systems", "",
              "CLI scenarios marked si_us were run twice: once in SI and once with every dimensioned number converted to US-customary units and passed "
              "through `--units us`. Python-API, JSON-tool and text-output scenarios are SI only; their inputs have no unit-bearing command-line "
              "flags, so `python -m process_safety convert` is how you prepare US values for them. See `docs/UNITS.md`.", ""]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--update", action="store_true")
    ap.add_argument("--only", help="run only scenario ids starting with this prefix")
    a = ap.parse_args(argv)
    if a.update:
        print(f"snapshots updated for {L.update_snapshots()} scenarios")
        return 0
    data = L.load()
    if a.only:
        data = {**data, "scenarios": [s for s in data["scenarios"] if s["id"].startswith(a.only)]}
    results = L.run_all(data)
    for r in results:
        for c in r["checks"]:
            if not c["ok"]:
                print(f"FAIL {r['id']} [{c['kind']}] {c['name']}: {c['detail']}")
    n_ok = sum(r["ok"] for r in results)
    if a.write and not a.only:
        with open(REPORT, "w", encoding="utf-8") as fh:
            fh.write(report(data, results))
    if n_ok == len(results):
        print(f"SCENARIOS PASS {n_ok}/{len(results)}")
        return 0
    print(f"SCENARIOS FAIL {len(results) - n_ok} of {len(results)}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
